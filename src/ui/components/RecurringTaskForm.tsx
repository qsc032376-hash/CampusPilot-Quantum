import { useEffect, useId, useState } from 'react';
import type { FormEvent } from 'react';
import type { TaskSeries } from '../../features/recurring-tasks/index.ts';
import {
  ISO_WEEKDAYS,
  MAX_SERIES_DURATION,
  MAX_SERIES_TITLE,
  describeRule,
  draftToSeries,
  hasSeries,
  emptyDraft,
  occurrenceCount,
  seriesToDraft,
  validateDraft,
} from '../recurring.ts';
import type { SeriesDraft } from '../recurring.ts';
import type { CampusLocation } from '../../types.ts';
import { TaskLocationField } from './TaskLocationField.tsx';
import { OptionalDetails } from './OptionalDetails.tsx';
import { buildTaskLocation, locationSummary } from '../taskLocationDraft.ts';
import type { TaskLocation } from '../../types.ts';

export interface OneOffFromSeries {
  title: string;
  durationMinutes: number;
  dueAt: string;
  priority?: 'low' | 'medium' | 'high';
  courseCode?: string;
  /** Explicit location carried over from the repeating draft; undefined only for legacy. */
  location?: TaskLocation;
}

interface RecurringTaskFormProps {
  series: readonly TaskSeries[];
  /** Campus catalog used for the per-series location choice. */
  locations: readonly CampusLocation[];
  /** Calendar dates of the current range, used only to count occurrences. */
  dates: readonly string[];
  defaultStartDate: string;
  rangeStart: string;
  rangeEnd: string;
  /** End of the study window for a date, used as the due time of a single entry. */
  dueAtFor: (date: string) => string | null;
  onAddSeries: (series: TaskSeries) => void;
  onUpdateSeries: (series: TaskSeries) => void;
  onDeleteSeries: (id: string) => void;
  onAddOneOff: (task: OneOffFromSeries) => void;
}

let seriesCounter = 0;
function makeSeriesId(): string {
  seriesCounter += 1;
  return `series-${Date.now().toString(36)}-${seriesCounter}`;
}

/**
 * Every entry keeps the original TaskSeries in state; occurrences are only ever
 * generated by A's adapter. Editing keeps the series id so a selected occurrence
 * survives when its date still exists.
 */
export function RecurringTaskForm({
  series,
  locations,
  dates,
  defaultStartDate,
  rangeStart,
  rangeEnd,
  dueAtFor,
  onAddSeries,
  onUpdateSeries,
  onDeleteSeries,
  onAddOneOff,
}: RecurringTaskFormProps) {
  const [draft, setDraft] = useState<SeriesDraft>(() => emptyDraft(defaultStartDate, locations));
  const [editingId, setEditingId] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [startTouched, setStartTouched] = useState(false);
  /** Editing a series whose location is undefined keeps that legacy choice until changed. */
  const [legacyEditing, setLegacyEditing] = useState(false);
  const [detailsOpen, setDetailsOpen] = useState(false);
  /** Which field the current error belongs to, so it can be associated with that input. */
  const [errorField, setErrorField] = useState<'title' | 'location' | null>(null);
  const fieldId = useId();

  // The start date follows the viewed day until the user edits it or opens a
  // series for editing, so a new series never defaults to a stale date.
  useEffect(() => {
    if (startTouched || editingId) return;
    setDraft((current) => (current.startDate === defaultStartDate ? current : { ...current, startDate: defaultStartDate }));
  }, [defaultStartDate, editingId, startTouched]);

  function patch(next: Partial<SeriesDraft>) {
    setDraft((current) => ({ ...current, ...next }));
  }

  function resetDraft() {
    setDraft(emptyDraft(defaultStartDate, locations));
    setEditingId(null);
    setError(null);
    setStartTouched(false);
    setLegacyEditing(false);
  }

  function handleSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();

    // The series being edited can disappear from the list; never silently drop
    // the user's draft or pretend an update happened.
    if (editingId && !hasSeries(series, editingId)) {
      setEditingId(null);
      setError(
        'That repeating series no longer exists, so your draft was kept. Review it and add it as a new series.',
      );
      return;
    }
    const message = validateDraft(draft, locations);
    if (message) {
      setError(message);
      setErrorField(/title/i.test(message) ? 'title' : /name/i.test(message) ? 'location' : null);
      return;
    }

    if (editingId && draft.frequency === 'never') {
      setError('Choose Daily or Weekly when editing a repeating series.');
      return;
    }

    if (draft.frequency === 'never') {
      if (draft.startDate < rangeStart || draft.startDate > rangeEnd) {
        setError('Pick a start date inside the selected range for a single task.');
        return;
      }
      const dueAt = dueAtFor(draft.startDate);
      if (!dueAt) {
        setError('That day has no study window in the selected range.');
        return;
      }
      const located = buildTaskLocation(draft.location, locations);
      if (!located.ok) {
        setError(located.message);
        return;
      }
      onAddOneOff({
        title: draft.title.trim(),
        durationMinutes: draft.durationMinutes,
        dueAt,
        ...(draft.priority ? { priority: draft.priority } : {}),
        ...(draft.courseCode.trim() ? { courseCode: draft.courseCode.trim() } : {}),
        ...(located.location ? { location: located.location } : {}),
      });
      resetDraft();
      return;
    }

    const id = editingId ?? makeSeriesId();
    const built = draftToSeries(draft, id, locations);
    if (editingId) onUpdateSeries(built);
    else onAddSeries(built);
    resetDraft();
  }

  /** Deleting the series being edited leaves a clean add form. */
  function handleDelete(id: string) {
    onDeleteSeries(id);
    if (id === editingId) resetDraft();
  }

  function startEdit(item: TaskSeries) {
    setDraft(seriesToDraft(item, locations));
    setEditingId(item.id);
    setError(null);
    setStartTouched(true);
    // An undefined location stays undefined unless the user picks a new value.
    setLegacyEditing(item.location === undefined);
  }

  function toggleWeekday(day: number) {
    setDraft((current) => ({
      ...current,
      weekdays: current.weekdays.includes(day)
        ? current.weekdays.filter((value) => value !== day)
        : [...current.weekdays, day],
    }));
  }

  const repeating = draft.frequency !== 'never';
  const unit = draft.frequency === 'daily' ? 'day' : 'week';

  return (
    <section className="cp-task-block" aria-labelledby="cp-recurring-heading">
      <h3 id="cp-recurring-heading" className="cp-subhead">
        Repeating task
      </h3>
      <p className="cp-hint">Personal study plan · never a course or room booking</p>

      <form className="cp-form" onSubmit={handleSubmit} noValidate>
        <label className="cp-field" htmlFor={`${fieldId}-title`}>
          <span className="cp-field__label">Task</span>
          <input
            id={`${fieldId}-title`}
            className="cp-input"
            value={draft.title}
            aria-invalid={errorField === 'title'}
            aria-describedby={errorField === 'title' ? `${fieldId}-error` : undefined}
            maxLength={MAX_SERIES_TITLE + 20}
            autoComplete="off"
            onChange={(event) => {
              patch({ title: event.target.value });
              setError(null);
              setErrorField(null);
            }}
          />
        </label>

        <h4 id={`${fieldId}-pattern`} className="cp-subhead">
          Repeating pattern
        </h4>
        <div className="cp-field-row cp-field-row--split" role="group" aria-labelledby={`${fieldId}-pattern`}>
          <label className="cp-field" htmlFor={`${fieldId}-minutes`}>
            <span className="cp-field__label">Minutes</span>
            <input
              id={`${fieldId}-minutes`}
              className="cp-input"
              type="number"
              min={1}
              max={MAX_SERIES_DURATION}
              step={15}
              value={draft.durationMinutes}
              onChange={(event) => patch({ durationMinutes: Number(event.target.value) })}
            />
          </label>

          <label className="cp-field" htmlFor={`${fieldId}-frequency`}>
            <span className="cp-field__label">Repeats</span>
            <select
              id={`${fieldId}-frequency`}
              className="cp-input"
              value={draft.frequency}
              onChange={(event) => patch({ frequency: event.target.value as SeriesDraft['frequency'] })}
            >
              <option value="never" disabled={editingId !== null}>
                Never
              </option>
              <option value="daily">Daily</option>
              <option value="weekly">Weekly</option>
            </select>
          </label>
        </div>

        {repeating && (
          <div className="cp-field-row cp-field-row--split">
            <label className="cp-field" htmlFor={`${fieldId}-interval`}>
              <span className="cp-field__label">Every</span>
              <input
                id={`${fieldId}-interval`}
                className="cp-input"
                type="number"
                min={1}
                max={30}
                step={1}
                value={draft.interval}
                onChange={(event) => patch({ interval: Number(event.target.value) })}
              />
            </label>
            <p className="cp-field__hint" aria-live="polite">
              {draft.interval === 1 ? `Every ${unit}` : `Every ${draft.interval} ${unit}s`}
            </p>
          </div>
        )}

        {draft.frequency === 'weekly' && (
          <fieldset className="cp-fieldset">
            <legend className="cp-field__label">Weekdays</legend>
            <div className="cp-weekdays">
              {ISO_WEEKDAYS.map((day) => (
                <label key={day.value} className="cp-weekday">
                  <input
                    type="checkbox"
                    checked={draft.weekdays.includes(day.value)}
                    onChange={() => toggleWeekday(day.value)}
                  />
                  <span>{day.short}</span>
                </label>
              ))}
            </div>
          </fieldset>
        )}

        <div className="cp-field-row cp-field-row--split">
          <label className="cp-field" htmlFor={`${fieldId}-start`}>
            <span className="cp-field__label">Starts (New York)</span>
            <input
              id={`${fieldId}-start`}
              className="cp-input"
              type="date"
              value={draft.startDate}
              onChange={(event) => {
                setStartTouched(true);
                patch({ startDate: event.target.value });
              }}
            />
          </label>

          <label className="cp-field" htmlFor={`${fieldId}-end`}>
            <span className="cp-field__label">Ends (optional, inclusive)</span>
            <input
              id={`${fieldId}-end`}
              className="cp-input"
              type="date"
              value={draft.endDate}
              onChange={(event) => patch({ endDate: event.target.value })}
            />
          </label>
        </div>

        <OptionalDetails
          summary={locationSummary(draft.location, locations)}
          open={detailsOpen || error !== null}
          onOpenChange={setDetailsOpen}
        >
          <div className="cp-field-row cp-field-row--split">
            <label className="cp-field" htmlFor={`${fieldId}-priority`}>
            <span className="cp-field__label">Priority (optional)</span>
            <select
              id={`${fieldId}-priority`}
              className="cp-input"
              value={draft.priority}
              onChange={(event) => patch({ priority: event.target.value as SeriesDraft['priority'] })}
            >
              <option value="">None</option>
              <option value="low">Low</option>
              <option value="medium">Medium</option>
              <option value="high">High</option>
            </select>
          </label>

          <label className="cp-field" htmlFor={`${fieldId}-course`}>
            <span className="cp-field__label">Course code (optional)</span>
            <input
              id={`${fieldId}-course`}
              className="cp-input"
              value={draft.courseCode}
              maxLength={16}
              onChange={(event) => patch({ courseCode: event.target.value })}
            />
          </label>
        </div>

        <p className="cp-hint">
          {repeating
            ? 'Each occurrence is due at the end of that day’s study window and can only be placed inside that day.'
            : 'Never repeating adds one task, due at the end of the chosen day’s study window.'}
        </p>

        {error && (
          <p className="cp-error" role="alert" id={`${fieldId}-error`}>
            {error}
          </p>
        )}

        <TaskLocationField
          idPrefix={fieldId}
          locations={locations}
          draft={draft.location}
          onChange={(next) => {
            patch({ location: next });
            setError(null);
            setErrorField(null);
          }}
          allowLegacy={editingId !== null && legacyEditing}
          describedBy={errorField === 'location' ? `${fieldId}-error` : undefined}
          invalid={errorField === 'location'}
        />
        </OptionalDetails>

        <div className="cp-form__actions">
          <button type="submit" className="cp-button">
            {editingId ? 'Save changes' : 'Add repeating task'} <span aria-hidden="true">+</span>
          </button>
          {editingId && (
            <button type="button" className="cp-link" onClick={resetDraft}>
              Cancel
            </button>
          )}
        </div>
      </form>

      <h3 className="cp-subhead">Repeating series</h3>
      {series.length === 0 ? (
        <p className="cp-hint">No repeating tasks yet.</p>
      ) : (
        <ul className="cp-series">
          {series.map((item) => {
            const count = occurrenceCount(item, dates);
            return (
              <li key={item.id} className={`cp-series__row${editingId === item.id ? ' is-editing' : ''}`}>
                <span className="cp-series__title">{item.title}</span>
                <span className="cp-series__meta">
                  {describeRule(item)} · {item.durationMinutes} min · {item.startDate}
                  {item.endDate ? ` – ${item.endDate}` : ''} · {count} occurrence{count === 1 ? '' : 's'} in range
                </span>
                <span className="cp-series__actions">
                  <button
                    type="button"
                    className="cp-link"
                    onClick={() => startEdit(item)}
                    aria-label={`Edit ${item.title}`}
                  >
                    Edit
                  </button>
                  <button
                    type="button"
                    className="cp-link"
                    onClick={() => handleDelete(item.id)}
                    aria-label={`Delete ${item.title}`}
                  >
                    Delete
                  </button>
                </span>
              </li>
            );
          })}
        </ul>
      )}
    </section>
  );
}
